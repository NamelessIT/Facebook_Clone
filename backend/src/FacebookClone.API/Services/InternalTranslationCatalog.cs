    public static string? Find(string sourceLocale, string targetLocale, string text)
    {
        if (sourceLocale.Equals("vi", StringComparison.OrdinalIgnoreCase) &&
            targetLocale.Equals("en", StringComparison.OrdinalIgnoreCase) &&
            VietnameseToEnglish.TryGetValue(text.Trim(), out var english)) return english;

        if (sourceLocale.Equals("en", StringComparison.OrdinalIgnoreCase) &&
            targetLocale.Equals("vi", StringComparison.OrdinalIgnoreCase))
            return VietnameseToEnglish.FirstOrDefault(x => x.Value.Equals(text.Trim(), StringComparison.OrdinalIgnoreCase)).Key;

        return null;
    }
